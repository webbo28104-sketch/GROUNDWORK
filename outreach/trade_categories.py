"""
Trade categories and UK search areas for the outreach sourcer.

TRADE_CATEGORIES is the canonical list of (search_term, canonical_name, tier)
tuples. The search_term is what we actually send to the Places API; the
canonical_name is the tidy label we store/display; the tier drives the scorer's
trade-tier points (high=20, medium=12, low=5).

UK_AREAS is the search grid's geography. REVISED 2026-07-21 (sourcing
capacity expansion) — previously a hand-typed list of ~353 town/city names.
Replaced wholesale with 2,834 real UK postcode districts (e.g. "SW1A", "M1",
"YO21"), sourced from a public postcode-district dataset (gibbs/uk-postcodes
on GitHub, cross-checked against Wikipedia's postcode-area district ranges)
and verified live against the actual Google Places API this pipeline calls.
2,834 is genuinely ~all of them — there are about 2,857 UK postcode districts
nationally; the ~23 excluded here are Crown Dependencies (Jersey/Guernsey/
Isle of Man), out of scope for a regionCode=GB Places search anyway.

Why postcode districts, and why each one is paired with a real town/borough
name (AREA_SEARCH_QUALIFIER below) rather than searched bare: a live test
against the real Places API confirmed a bare postcode district is genuinely
unreliable on its own -- "plumber in M1" alone returned Brighton results, not
Manchester (M1 is also read as the motorway / ambiguous by Google's own
text-query geocoding), while "plumber in M1, Manchester" resolved correctly.
So outreach/pipeline.py builds every query as "{trade} in {district}, {town}"
using this mapping, never a bare code. The qualifier is the dataset's own
per-district town name, falling back to its region/borough name for the ~554
districts (mostly city-centre codes like Birmingham's B1-B19) whose town
field was blank but whose region field was populated and just as reliable
(e.g. B1's region is literally "Birmingham"). 11 districts had neither a
usable town nor a clean-enough region string (garbled multi-parish names) and
are searched on the bare code only -- a real, small, deliberately-not-guessed
gap rather than a fabricated qualifier.

Geographic granularity is the single biggest capacity lever, but it does NOT
apply evenly: of the 2,834 districts, roughly 1,700+ are under towns that had
NO existing search cell at all before this change (genuine new market
coverage), while a few hundred are finer subdivisions of the ~60 largest
cities/towns that already had one (London, Manchester, Birmingham, Bristol,
etc.) -- that subdivision mostly recovers businesses beyond position 20/60 of
what a whole-city search already returns, not a proportionally new market.
Expect real yield per new cell in an already-covered big city to be well
below the grid-wide average, not "however many districts a city has, times
the old single-cell yield."

AREA_INCOME_TIER tags each area with a rough regional income band (high/medium/
low), from ONS regional gross disposable household income (GDHI) per head --
London & the South East highest, North East/Wales/Yorkshire/Northern Ireland
lowest, everywhere else medium (ons.gov.uk/economy/regionalaccounts/
grossdisposablehouseholdincome). This is a *region-level* grouping (assigned
per postcode district's real ONS region from the same source dataset), not a
per-city ranking -- area-level noise isn't worth chasing for what this is
actually used for: making sure sourcing doesn't get stuck in one economic
bracket for weeks (see get_pending_cells' shuffle).
"""

